#!/usr/bin/env node
'use strict';
/**
 * report-honesty.js - Stop. Отчёт в чат должен быть правдой.
 *
 * Владелец дифф не читает и вывод команд не смотрит: он читает семь строк отчёта -
 * ровно столько, сколько допускает answerFormat.maxLines и сверяет obvyazka-selftest.js.
 * Значит, единственный способ тихо сломать весь режим - написать в отчёте то, чего не было.
 * Хук берёт последний ответ ассистента и сверяет его утверждения с состоянием.
 *
 * Предметов три, и все три - про расхождение отчёта с фактом:
 *
 *   1. «Проверки зелёные» без прогона. Требуется запись lastGates с кодом возврата 0
 *      и с отпечатком ТЕКУЩЕГО диффа (отпечаток считает diff-hash.js, тот же, что
 *      у commit-gate). Отпечаток нужен не меньше кода возврата: гейты, прогнанные
 *      до последней правки, про неё ничего не знают, а фраза «зелено» в отчёте звучит
 *      одинаково в обоих случаях.
 *
 *   2. Обвязка менялась, но не уехала в origin. У бэкенда есть тег, конвейер и откат;
 *      у фронта блю-грин; у правил, которые всем этим управляют, - ничего: файл лёг
 *      на диск, и следующая сессия уже работает по нему. Пока правка не в origin, она
 *      живёт на одной машине и восстановить её неоткуда.
 *
 *   3. Строка «Обвязка:» в отчёте говорит «не менялась», когда обвязка менялась.
 *      Правка протокола иначе неотличима от правки документации: владелец узнаёт о ней,
 *      только читая дифф, а дифф он не читает.
 *
 * 🔴 Предметы 2 и 3 проверяются ТОЛЬКО на закрывающем отчёте, и это граница, а не
 * послабление (решение арбитра 02.09.2026, decisions-log.md). Грязное дерево `.claude`
 * в середине захода - штатное состояние: гейты идут шагом 8, коммит шагом 10. Проверять
 * это раньше значило бы требовать закоммиченную обвязку до того, как её разрешено
 * коммитить. На закрывающем отчёте грязное дерево - уже не фаза работы, а незаконченная
 * работа, названная законченной.
 *
 * Хук ничего не запрещает - он возвращает работу агенту: либо доделать, либо написать
 * в отчёте то, что есть на самом деле.
 */

const L = require('./lib.js');
const H = require('./diff-hash.js');

/**
 * Утверждения о зелёных проверках. Ищем именно утверждение, а не слово «тест»:
 * «осталось прогнать гейты» - не заявление о результате.
 *
 * Границы слов заданы явными просмотрами, а не \b: в JavaScript \b считает словом
 * только латиницу, и вокруг кириллицы он не срабатывает вовсе.
 */
const RU = '[а-яёА-ЯЁ]';
const ru = (body) => new RegExp('(?<!' + RU + ')(?:' + body + ')(?!' + RU + ')', 'i');

const GREEN = [
  ru('зелен[оаы]'),
  ru('зелён(?:ый|ая|ые|ое|о)'),
  ru('вс[её]\\s+(?:прошл[оа]|проходит|чисто|ок|зелен|зелён)'),
  ru('проверки\\s+(?:в\\s+порядке|прошли|проход[яи]т|чист|зелен|зелён)'),
  ru('гейты\\s+(?:прошли|в\\s+порядке|чист|зелен|зелён)'),
  ru('тесты\\s+(?:прошли|проход[яи]т|зелен|зелён)'),
  ru('(?:типизация|линт|сборка|билд)\\s+(?:прошл|чист|зелен|зелён|без\\s+ошибок)'),
  ru('без\\s+ошибок'),
  /\bCI\s+(?:зел|green|прош)/i,
  /\ball\s+(?:tests\s+)?(?:pass|green)/i,
];

function claimsGreen(text) {
  return GREEN.some((re) => re.test(text));
}

function render(problem) {
  return (
    'В ответе сказано, что проверки зелёные, а подтверждения этому нет: ' + problem + '.\n' +
    'Отчёт владельцу - единственное, что он читает; неподтверждённое «зелено» в нём хуже\n' +
    'красного гейта, потому что его никто не перепроверит.\n\n' +
    'Сделай одно из двух:\n' +
    '  - прогони проверки по-настоящему: node .claude/hooks/gates.js (без --repo),\n' +
    '    добейся нулевого кода возврата и только потом пиши про зелёное;\n' +
    '  - убери из ответа утверждение о зелёных проверках и напиши, что на самом деле есть.\n'
  );
}

/**
 * Закрывающий ли это отчёт.
 *
 * 🔴 Признак берётся из формы отчёта, а не из догадки о намерении. Форма задана
 * в commands/auto.md и tech-debt-autopilot.md.
 *
 * Меток две группы, и деление между ними - не украшение, а два пойманных дефекта.
 *
 * ЗАКРЫВАЮЩИЕ метки («Решено за тебя», «Уехало на прод», «Обвязка») встречаются только
 * в итоговом отчёте: в промежуточном ходе их не пишут. По ним и опознаётся закрытие.
 *
 * ⚠️ «Осталось» и «Дальше» в счёт НЕ идут, хотя стоят в той же форме. Первая редакция их
 * считала - и останавливала посреди работы: ход «Осталось: разобраться, почему воркер
 * не забирает джобу. Дальше: посмотрю логи redis» давал две метки и признавался закрывающим,
 * а дерево обвязки на шаге 8 из 10 грязное штатно. Ложная остановка здесь дороже пропуска:
 * проверку, мешающую работать, снимают целиком.
 *
 * ⚠️ Обёртка markdown допускается явно: `**Обвязка:**`, `- Обвязка:`, `> Обвязка:`.
 * Первая редакция требовала метку голой, и закрывающий отчёт с жирными метками проходил
 * молча вместе с враньём в строке «Обвязка:» - воспроизведено ревью.
 *
 * Встречный признак - прямое утверждение о законченности. Без него отчёт, написанный
 * не по форме, проверку обходил бы, а «сделано» без сделанного - ровно то, что здесь ловится.
 */

/** Метка отчёта в начале строки, с любой разметкой вокруг: **Метка:**, - Метка:, > Метка: */
const label = (body) => new RegExp('^[\\s>*_\\-]*\\*{0,2}\\s*(?:' + body + ')\\s*\\*{0,2}\\s*:', 'im');

const CLOSING_LABELS = [
  label('Решено\\s+за\\s+тебя'),
  label('Задача'),
  label('Обвязка'),
];

const DONE_CLAIM = [
  ru('задача\\s+(?:закрыта|сделана|готова)'),
  ru('заход\\s+(?:закрыт|закончен|завершён|завершен)'),
  ru('работа\\s+(?:закончена|завершена|сделана)'),
  ru('(?:всё|все)\\s+(?:сделано|готово|закрыто)'),
  ru('пачка\\s+(?:закрыта|закончена)'),
];

function isClosingReport(text) {
  if (CLOSING_LABELS.filter((re) => re.test(text)).length >= 2) return true;
  return DONE_CLAIM.some((re) => re.test(text));
}

/** Строка «Обвязка:» из отчёта, если она есть. Разметка вокруг метки допускается. */
function harnessLine(text) {
  const m = /^[\s>*_\-]*\*{0,2}\s*Обвязка\s*\*{0,2}\s*:\s*\*{0,2}\s*(.+)$/im.exec(text);
  return m ? m[1].replace(/\*+\s*$/, '').trim() : null;
}

/**
 * Состояние обвязки: менялась ли за заход и уехала ли.
 *
 * Возвращает { touched, dirty, ahead, problem }. `problem` - это отказ самой проверки
 * (git не отработал), и он тоже красный: «я не смогла проверить» здесь не то же самое,
 * что «всё хорошо».
 */
function harnessState() {
  const repo = L.knownRepos().find((r) => r.name === '.claude');
  if (!repo) {
    return { problem: 'обвязки нет в repos.json - её состояние нечем проверить' };
  }
  // Обёртка git берётся из lib.js, а не заводится своя: там уже есть maxBuffer, windowsHide
  // и глушение исключения спавна. Вторая копия разошлась бы с первой при первой же правке.
  const git = (args) => L.sh('git', args, repo.path);

  const status = git(['--no-optional-locks', 'status', '--porcelain']);
  if (!status.ok) {
    return { problem: 'git status в .claude не отработал: ' + String(status.err || '').trim() };
  }
  const dirty = String(status.out || '').split('\n').filter(Boolean);

  const upstream = git(['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{upstream}']);
  if (!upstream.ok) {
    return { dirty, problem: 'у ветки обвязки нет upstream - её правки никуда не уезжают' };
  }

  // 🔴 Код возврата проверяется до разбора вывода, а не после.
  //
  // Прежде здесь стояло только Number.isFinite от разобранного stdout - и отказ `rev-list`
  // давал пустую строку, `Number('')` давал 0, а ноль означает «всё отправлено». То есть
  // «я не смогла проверить» было неотличимо от «проверила, всё хорошо»: при чистом дереве
  // хук замолкал целиком, и закрывающий отчёт с «Обвязка: не менялась» проходил
  // при неотправленных коммитах. Нашло ревью, а не проба.
  const cnt = git(['rev-list', '--count', '@{upstream}..HEAD']);
  if (!cnt.ok) {
    return { dirty, problem: 'git rev-list в .claude не отработал: ' + String(cnt.err || '').trim() };
  }
  const raw = String(cnt.out || '').trim();
  if (!/^\d+$/.test(raw)) {
    return { dirty, problem: 'не удалось сосчитать неотправленные коммиты обвязки: «' + raw + '»' };
  }
  const ahead = Number(raw);

  // Менялась ли обвязка за заход: её файлы в отпечатке захода либо незакоммиченные правки.
  const touched =
    dirty.length > 0 || ahead > 0 || H.diffLabels().some((l) => l.startsWith('.claude/'));

  return { touched, dirty, ahead };
}

function renderHarness(problem) {
  return (
    'Отчёт закрывает заход, а с обвязкой не сходится: ' + problem + '.\n' +
    'Обвязка - единственное место в проекте, где правка применяется мгновенно и без окна\n' +
    'отказа: у бэкенда есть тег и откат, у фронта блю-грин, у правил - ничего. Пока правка\n' +
    'не в origin, она живёт на одной машине, и восстановить её неоткуда.\n\n' +
    'Сделай одно из двух:\n' +
    '  - доведи до конца: закоммить и отправь правки обвязки;\n' +
    '  - если коммит в этом заходе не предусмотрен, напиши это в отчёте прямо, а не строкой\n' +
    '    «не менялась» - владелец должен узнать о правке протокола из отчёта, а не из диффа.\n'
  );
}

/**
 * Проверка утверждения о зелёных проверках. Возвращает текст замечания или null.
 *
 * 🔴 Вынесена в функцию и НЕ зовёт complain сама - вместе с предметами 2 и 3 она собирается
 * в один отказ. Иначе теряется, и вот как: `complain` завершает процесс (`lib.js:73-76`),
 * а второй заход хука глушится `stop_hook_active`. Значит первый сработавший предмет отменял бы
 * все следующие насовсем: сказал агент «всё зелено» при грязной обвязке - получил замечание
 * про обвязку, поправил обвязку, ответил снова, и утверждение о зелёном не проверилось уже
 * никем. Так новый предмет тихо снял бы старую проверку - ровно то, ради предотвращения чего
 * этот хук и написан.
 */
function greenProblem(text) {
  if (!claimsGreen(text)) return null;

  const state = L.readState();
  const labels = H.diffLabels();

  // 🔴 Пустой дифф не отменяет проверку утверждения.
  //
  // Прежде хук здесь молча выходил: «диффа нет - речь не о нашей работе». Но дифф
  // становится пустым сразу после коммита, то есть ровно в тот момент, когда пишется
  // отчёт о сделанном - и слово «зелено» в нём переставало проверяться вообще. Поймала
  // это самопроверка: её проба покраснела на чистом рабочем дереве, потому что хук
  // отвечал молчанием вместо отказа.
  //
  // Хук проверяет утверждение, а не дифф. Сказал «проверки зелёные» - значит где-то был
  // прогон с кодом 0. При пустом диффе отпечаток не сверяется (сравнивать не с чем),
  // но сама отметка обязана быть.
  if (!labels.length) {
    const g = state && state.lastGates;
    if (g && typeof g === 'object' && Number(g.code) === 0) return null;
    return render(
      g && typeof g === 'object'
        ? 'последний прогон гейтов упал, код возврата ' + g.code
        : 'гейты не гонялись ни разу, а рабочее дерево чистое - подтвердить нечем',
    );
  }

  const problem = H.gatesProblem(state, H.diffHash(labels), labels);
  return problem ? render(problem) : null;
}

/**
 * Заход, в котором коммит не предусмотрен: владелец забрал его себе.
 *
 * 🔴 Ветка нужна, и она не послабление. Правило «правка обвязки не сделана, пока не уехала
 * в origin» верно для обычного захода, где агент коммитит сам. Но бывает заход по прямому
 * заданию владельца, где коммит запрещён прямым текстом, а дифф отдаётся ему на ревью, -
 * и без этой ветки такой заход не смог бы сдать отчёт вовсе: хук требовал бы отправки,
 * которую задание запрещает. Непреодолимая проверка снимается первой же следующей сессией.
 *
 * Послабление узкое: агент обязан **назвать** это в отчёте прямо. Умолчать нельзя - при
 * умолчании работает обычное правило и хук останавливает. То есть проверка не снимается,
 * а меняет предмет: вместо «отправь» она требует «скажи владельцу, что не отправлено и почему».
 *
 * ⚠️ Формулировки нарочно узкие, и вот почему. Первая редакция ловила ещё «коммита нет»
 * и «коммитов не было» - и снималась на посторонних фразах вроде «коммитов нет
 * в books-front, там не менялось ничего»: обычный отчёт обычного захода тихо переставал
 * проверяться. Признаком считается только утверждение **о своей работе целиком**, где сказано,
 * что коммит не делался или что дифф отдан владельцу. Расширять этот список без пробы
 * на ложное срабатывание нельзя: каждая новая формулировка - это ещё один способ снять
 * проверку, ничего не нарушив.
 */
const NO_COMMIT_DECLARED = [
  /коммит(?:а|ов)?\s+не\s+делал/i,
  /без\s+коммита\s+и\s+пуша/i,
  /ждёт\s+ревью\s+владельца/i,
  /ждут\s+ревью\s+владельца/i,
  /владелец\s+коммитит\s+сам/i,
];

function declaresNoCommit(text) {
  return NO_COMMIT_DECLARED.some((re) => re.test(text));
}

/** Замечания про обвязку на закрывающем отчёте. Массив текстов, возможно пустой. */
function harnessProblems(text) {
  if (!isClosingReport(text)) return [];

  // Обвязка лежит внутри репозитория продукта (rules.common.json: harnessRepo=false):
  // своего git у неё нет, коммитится она вместе с кодом, и проверять здесь остаётся
  // одно - не врёт ли строка «Обвязка:» про то, что она не менялась.
  if (L.commonRules().harnessRepo === false) {
    const touched = H.diffLabels().some((l) => /(^|\/)\.claude\//.test(l));
    const line = harnessLine(text);
    if (touched && line && /^не\s+менял/i.test(line)) {
      return [renderHarness('строка «Обвязка:» говорит «не менялась», а файлы .claude/** есть в диффе захода')];
    }
    return [];
  }

  const h = harnessState();
  if (h.problem) return [renderHarness(h.problem)];
  if (!h.touched) return [];

  // Коммит объявлен ненужным - остаётся одна проверка: строка «Обвязка:» всё равно не смеет врать.
  if (declaresNoCommit(text)) {
    const line = harnessLine(text);
    if (line && /^не\s+менял/i.test(line)) {
      return [
        renderHarness(
          'строка «Обвязка:» говорит «не менялась», а обвязка в этом заходе менялась. ' +
            'То, что коммит не предусмотрен, эту строку не отменяет: владелец должен узнать ' +
            'о правке протокола из отчёта',
        ),
      ];
    }
    return [];
  }

  const out = [];
  const line = harnessLine(text);
  if (line && /^не\s+менял/i.test(line)) {
    out.push(
      renderHarness('строка «Обвязка:» говорит «не менялась», а обвязка в этом заходе менялась'),
    );
  }
  if (h.dirty.length) {
    out.push(
      renderHarness(
        'дерево .claude грязное, файлов ' + h.dirty.length + ' (' +
          h.dirty.slice(0, 4).map((l) => l.slice(3).trim()).join(', ') +
          (h.dirty.length > 4 ? ' и ещё ' + (h.dirty.length - 4) : '') + ')',
      ),
    );
  }
  if (h.ahead > 0) {
    out.push(renderHarness(h.ahead + ' коммит(ов) обвязки не отправлено в origin'));
  }
  return out;
}

L.guard(async () => {
  const input = await L.readStdin();
  // замечание уже выдано - второй заход молчит, иначе получится петля
  if (input && input.stop_hook_active === true) return;

  const text = L.lastAssistantText(input && input.transcript_path);
  if (!text) return;

  // Все предметы собираются и выдаются одним отказом: см. комментарий к greenProblem.
  const problems = harnessProblems(text);
  const green = greenProblem(text);
  if (green) problems.push(green);

  if (problems.length) L.complain(problems.join('\n'));
});
